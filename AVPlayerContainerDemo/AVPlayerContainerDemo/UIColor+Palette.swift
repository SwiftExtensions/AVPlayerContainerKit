import UIKit

/**
 Палитра демо-приложения.

 Цвета заданы в каталоге ресурсов с вариантами светлой и тёмной темы.
 */
extension UIColor {
    /**
     Фон плейлиста и плеера.
     */
    static let playlistBackground = UIColor(named: "PlaylistBackground")!
    /**
     Подсветка выбранной ячейки потока.
     */
    static let streamSelection = UIColor(named: "StreamSelection")!
    /**
     Фон заголовка группы.
     */
    static let groupHeader = UIColor(named: "GroupHeader")!


}


