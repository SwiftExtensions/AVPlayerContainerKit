/**
 Снимок состояния группы потоков вещания для отображения в таблице.

 Содержит координаты группы в плейлисте и индексы её отображаемых строк.
 */
struct GroupSnapshot {
    /**
     Индекс секции группы в плейлисте.
     */
    let playlistSection: Int
    /**
     Индексы отображаемых строк группы в плейлисте.
     */
    let playlistRows: [Int]


}


